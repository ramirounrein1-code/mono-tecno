-- Intentos fallidos de entrar al panel (para frenar ataques de fuerza bruta)
create table if not exists privado.intentos (
  ip text not null,
  momento timestamptz not null default now()
);

-- ---------- Tablas públicas ----------
create table if not exists public.productos (
  id text primary key,
  sku text not null unique,
  nombre text not null check (char_length(nombre) between 3 and 120),
  marca text not null default '',
  categoria text not null,
  condicion text not null default 'Usado' check (condicion in ('Nuevo', 'Usado', 'Reacondicionado')),
  precio integer not null check (precio >= 0),
  stock integer not null default 0 check (stock between 0 and 999),
  stock_guardado integer,
  destacado boolean not null default false,
  fecha_alta date not null default current_date,
  imagen text not null default '' check (char_length(imagen) <= 400000),
  specs text not null default '',
  descripcion text not null default '',
  ficha jsonb not null default '[]',
  ideal jsonb not null default '[]',
  actualizado timestamptz not null default now()
);

create table if not exists public.pedidos (
  numero bigint generated by default as identity (start with 1001) primary key,
  token uuid not null default gen_random_uuid(),
  estado text not null default 'Pendiente de pago'
    check (estado in ('Pendiente de pago', 'Pagado', 'Enviado', 'Entregado', 'Cancelado')),
  vencido boolean not null default false,
  fecha timestamptz not null default now(),
  items jsonb not null,
  subtotal integer not null,
  envio integer not null,
  descuento integer not null,
  total integer not null,
  cliente jsonb not null,
  entrega jsonb not null,
  pago text not null check (pago in ('mercadoPago', 'transferencia', 'efectivo')),
  usuario text,
  ip text
);
create index if not exists pedidos_email on public.pedidos ((lower(cliente->>'email')), estado);
create index if not exists pedidos_ip on public.pedidos (ip, fecha);

-- Seguridad por filas: el catálogo se puede leer; los pedidos NO se pueden leer ni escribir directo.
alter table public.productos enable row level security;
alter table public.pedidos enable row level security;
drop policy if exists "catalogo publico" on public.productos;
create policy "catalogo publico" on public.productos for select using (true);
grant usage on schema public to anon, authenticated;
grant select on public.productos to anon, authenticated;
revoke insert, update, delete on public.productos from anon, authenticated;
revoke all on public.pedidos from anon, authenticated;

-- ---------- Funciones internas ----------
-- IP de quien llama (la manda Supabase en los encabezados)
create or replace function privado.ip() returns text
language sql stable as $$
  select coalesce(nullif(trim(split_part(coalesce(current_setting('request.headers', true)::json->>'x-forwarded-for', ''), ',', 1)), ''), 'desconocida')
$$;

-- Comprueba la clave del panel. Devuelve NULL si está bien, o el motivo del rechazo.
-- No corta con error a propósito: así el intento fallido queda guardado (un error desharía el registro).
-- Más de 10 intentos fallidos en 15 minutos desde la misma IP bloquean.
create or replace function privado.es_admin(p_clave text) returns text
language plpgsql security definer set search_path = privado, public, extensions as $$
declare
  v_ip text := privado.ip();
  v_hash text;
begin
  if (select count(*) from privado.intentos where ip = v_ip and momento > now() - interval '15 minutes') >= 10 then
    return 'Demasiados intentos. Probá de nuevo en 15 minutos.';
  end if;
  select valor into v_hash from privado.ajustes where clave = 'admin_hash';
  if p_clave is null or encode(extensions.digest(p_clave, 'sha256'), 'hex') <> v_hash then
    insert into privado.intentos (ip) values (v_ip);
    return 'No autorizado. Volvé a entrar al panel.';
  end if;
  delete from privado.intentos where momento < now() - interval '1 day';
  return null;
end $$;

-- Guarda (crea o actualiza) un producto a partir de los datos del panel.
create or replace function privado.upsert_producto(p jsonb) returns public.productos
language plpgsql security definer set search_path = public as $$
declare v productos%rowtype;
begin
  insert into productos (id, sku, nombre, marca, categoria, condicion, precio, stock, stock_guardado, destacado, fecha_alta, imagen, specs, descripcion, ficha, ideal, actualizado)
  values (
    p->>'id', upper(p->>'sku'), p->>'nombre', coalesce(p->>'marca', ''), p->>'categoria', coalesce(p->>'condicion', 'Usado'),
    (p->>'precio')::int, (p->>'stock')::int, nullif(p->>'stockGuardado', '')::int, coalesce((p->>'destacado')::boolean, false),
    coalesce(nullif(p->>'fechaAlta', '')::date, current_date), coalesce(p->>'imagen', ''), coalesce(p->>'specs', ''),
    coalesce(p->>'descripcion', ''), coalesce(p->'ficha', '[]'), coalesce(p->'ideal', '[]'), now()
  )
  on conflict (id) do update set
    sku = excluded.sku, nombre = excluded.nombre, marca = excluded.marca, categoria = excluded.categoria,
    condicion = excluded.condicion, precio = excluded.precio, stock = excluded.stock, stock_guardado = excluded.stock_guardado,
    destacado = excluded.destacado, imagen = excluded.imagen, specs = excluded.specs, descripcion = excluded.descripcion,
    ficha = excluded.ficha, ideal = excluded.ideal, actualizado = now()
  returning * into v;
  return v;
end $$;

-- Pedidos sin pagar que pasaron las 48 h: se cancelan solos y el stock vuelve a la venta.
create or replace function public.expirar_pedidos() returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_pedido record;
  v_item jsonb;
  v_cant integer := 0;
begin
  for v_pedido in
    select numero, items from pedidos
    where estado = 'Pendiente de pago' and pago in ('transferencia', 'mercadoPago')
      and fecha < now() - interval '48 hours'
    for update skip locked
  loop
    for v_item in select * from jsonb_array_elements(v_pedido.items) loop
      update productos set stock = least(999, stock + (v_item->>'cantidad')::int) where id = v_item->>'id';
    end loop;
    update pedidos set estado = 'Cancelado', vencido = true where numero = v_pedido.numero;
    v_cant := v_cant + 1;
  end loop;
  return v_cant;
end $$;

-- ---------- Funciones públicas (las usa la tienda) ----------

-- Catálogo: antes de devolverlo libera las reservas vencidas.
create or replace function public.catalogo() returns setof public.productos
language plpgsql security definer set search_path = public as $$
begin
  perform expirar_pedidos();
  return query select * from productos order by fecha_alta desc, id;
end $$;

-- Crear un pedido. El precio, el envío y el descuento se calculan ACÁ con los datos reales,
-- y se aplican los límites contra quien quiera acaparar el stock.
create or replace function public.crear_pedido(
  p_items jsonb, p_cliente jsonb, p_entrega jsonb, p_pago text, p_usuario text default null
) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare
  c_por_producto constant int := 2;   -- unidades del mismo producto por pedido
  c_por_pedido constant int := 6;     -- unidades en total por pedido
  c_pendientes_email constant int := 2;
  c_pendientes_ip constant int := 3;
  c_pedidos_ip_hora constant int := 5;
  v_ip text := privado.ip();
  v_email text := lower(trim(coalesce(p_cliente->>'email', '')));
  v_tipo text := coalesce(p_entrega->>'tipo', '');
  v_item jsonb;
  v_prod productos%rowtype;
  v_cant int;
  v_total_unid int := 0;
  v_subtotal int := 0;
  v_envio int;
  v_desc int;
  v_items jsonb := '[]'::jsonb;
  v_numero bigint;
  v_token uuid;
  v_fecha timestamptz;
begin
  perform expirar_pedidos();

  -- Datos del cliente
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or char_length(v_email) > 120 then
    raise exception 'El email no es válido.';
  end if;
  if char_length(trim(coalesce(p_cliente->>'nombre', ''))) < 2 or char_length(trim(coalesce(p_cliente->>'apellido', ''))) < 2 then
    raise exception 'Completá nombre y apellido.';
  end if;
  if p_pago not in ('mercadoPago', 'transferencia', 'efectivo') then raise exception 'Medio de pago no válido.'; end if;
  if v_tipo not in ('retiro', 'moto', 'correo') then raise exception 'Forma de entrega no válida.'; end if;
  if p_pago = 'efectivo' and v_tipo <> 'retiro' then raise exception 'El efectivo es solo para retiro en persona.'; end if;

  -- Límites contra el acaparamiento de stock
  if (select count(*) from pedidos where lower(cliente->>'email') = v_email and estado = 'Pendiente de pago') >= c_pendientes_email then
    raise exception 'Ya tenés % pedidos sin pagar. Pagá o cancelá alguno antes de hacer otro.', c_pendientes_email;
  end if;
  if v_ip <> 'desconocida' then
    if (select count(*) from pedidos where ip = v_ip and estado = 'Pendiente de pago') >= c_pendientes_ip
       or (select count(*) from pedidos where ip = v_ip and fecha > now() - interval '1 hour') >= c_pedidos_ip_hora then
      raise exception 'Se hicieron demasiados pedidos desde esta conexión. Escribinos por Instagram y te ayudamos.';
    end if;
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then
    raise exception 'El carrito está vacío.';
  end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_cant := (v_item->>'cantidad')::int;
    if v_cant is null or v_cant < 1 then raise exception 'Cantidad no válida.'; end if;
    if v_cant > c_por_producto then
      raise exception 'Podés llevar hasta % unidades de cada producto por pedido.', c_por_producto;
    end if;
    v_total_unid := v_total_unid + v_cant;
    if v_total_unid > c_por_pedido then
      raise exception 'Un pedido puede tener hasta % unidades en total.', c_por_pedido;
    end if;
    -- Bloquea la fila: si dos personas compran la última unidad a la vez, solo una la consigue
    select * into v_prod from productos where id = v_item->>'id' for update;
    if not found then raise exception 'Un producto del carrito ya no existe.'; end if;
    if v_prod.stock < v_cant then
      raise exception 'No hay stock suficiente de "%" (quedan %).', v_prod.nombre, v_prod.stock;
    end if;
    update productos set stock = stock - v_cant, actualizado = now() where id = v_prod.id;
    v_subtotal := v_subtotal + v_prod.precio * v_cant;
    v_items := v_items || jsonb_build_object('id', v_prod.id, 'nombre', v_prod.nombre, 'precio', v_prod.precio, 'cantidad', v_cant);
  end loop;

  v_envio := case v_tipo when 'moto' then 7000 when 'correo' then 12000 else 0 end;
  v_desc := case when p_pago in ('transferencia', 'efectivo') then round(v_subtotal * 0.05) else 0 end;

  insert into pedidos (items, subtotal, envio, descuento, total, cliente, entrega, pago, usuario, ip)
  values (
    v_items, v_subtotal, v_envio, v_desc, v_subtotal - v_desc + v_envio,
    jsonb_build_object(
      'nombre', left(trim(p_cliente->>'nombre'), 40), 'apellido', left(trim(p_cliente->>'apellido'), 40),
      'email', v_email, 'telefono', left(coalesce(p_cliente->>'telefono', ''), 20), 'dni', left(coalesce(p_cliente->>'dni', ''), 10)
    ),
    p_entrega, p_pago, nullif(lower(trim(coalesce(p_usuario, ''))), ''), v_ip
  )
  returning numero, token, fecha into v_numero, v_token, v_fecha;

  return (select to_jsonb(p) - 'ip' from pedidos p where numero = v_numero);
end $$;

-- El cliente ve sus pedidos con el número y el código secreto que recibió al comprar.
create or replace function public.ver_pedidos(p_lista jsonb) returns jsonb
language sql security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(p) - 'ip' order by p.numero desc), '[]'::jsonb)
  from pedidos p
  join jsonb_array_elements(case when jsonb_typeof(p_lista) = 'array' then p_lista else '[]'::jsonb end) as e
    on p.numero = (e->>'numero')::bigint and p.token::text = e->>'token'
$$;

-- ---------- Funciones del panel (piden la clave) ----------
-- Todas devuelven {"error": "..."} si la clave no sirve, o el resultado si está bien.
create or replace function public.admin_verificar(p_clave text) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave);
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.admin_pedidos(p_clave text) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave);
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  perform expirar_pedidos();
  return jsonb_build_object('pedidos', (select coalesce(jsonb_agg(to_jsonb(p) - 'ip' order by p.numero desc), '[]'::jsonb) from pedidos p));
end $$;

create or replace function public.admin_guardar_producto(p_clave text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave);
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  if exists (select 1 from productos where upper(sku) = upper(p->>'sku') and id <> p->>'id') then
    return jsonb_build_object('error', 'Ya existe otro producto con ese SKU.');
  end if;
  return jsonb_build_object('producto', to_jsonb(privado.upsert_producto(p)));
end $$;

create or replace function public.admin_borrar_producto(p_clave text, p_id text) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave);
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  delete from productos where id = p_id;
  return jsonb_build_object('ok', true);
end $$;

-- Reemplaza todo el catálogo (botón "Restaurar catálogo" y primera carga)
create or replace function public.admin_restaurar(p_clave text, p_productos jsonb) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave); v jsonb; n int := 0;
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  delete from productos where true;
  for v in select * from jsonb_array_elements(p_productos) loop
    perform privado.upsert_producto(v);
    n := n + 1;
  end loop;
  return jsonb_build_object('cantidad', n);
end $$;

-- Cambia el estado. Cancelar devuelve el stock; "descancelar" lo vuelve a descontar.
create or replace function public.admin_estado_pedido(p_clave text, p_numero bigint, p_estado text) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave); v pedidos%rowtype; v_item jsonb; v_signo int := 0;
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  if p_estado not in ('Pendiente de pago', 'Pagado', 'Enviado', 'Entregado', 'Cancelado') then
    return jsonb_build_object('error', 'Estado no válido.');
  end if;
  select * into v from pedidos where numero = p_numero for update;
  if not found then return jsonb_build_object('error', 'El pedido no existe.'); end if;
  if p_estado = 'Cancelado' and v.estado <> 'Cancelado' then v_signo := 1; end if;
  if v.estado = 'Cancelado' and p_estado <> 'Cancelado' then v_signo := -1; end if;
  if v_signo <> 0 then
    for v_item in select * from jsonb_array_elements(v.items) loop
      update productos set stock = greatest(0, least(999, stock + v_signo * (v_item->>'cantidad')::int)) where id = v_item->>'id';
    end loop;
  end if;
  update pedidos set estado = p_estado, vencido = false where numero = p_numero;
  return jsonb_build_object('pedido', (select to_jsonb(p) - 'ip' from pedidos p where numero = p_numero));
end $$;

create or replace function public.admin_borrar_pedido(p_clave text, p_numero bigint) returns jsonb
language plpgsql security definer set search_path = public, privado as $$
declare v_err text := privado.es_admin(p_clave); v pedidos%rowtype; v_item jsonb;
begin
  if v_err is not null then return jsonb_build_object('error', v_err); end if;
  select * into v from pedidos where numero = p_numero for update;
  if found then
    if v.estado not in ('Entregado', 'Enviado', 'Cancelado') then
      for v_item in select * from jsonb_array_elements(v.items) loop
        update productos set stock = least(999, stock + (v_item->>'cantidad')::int) where id = v_item->>'id';
      end loop;
    end if;
    delete from pedidos where numero = p_numero;
  end if;
  return jsonb_build_object('ok', true);
end $$;

